import React from 'react';
import { useHousehold } from '../context/HouseholdContext';
import { inr } from '../components/common/bits';

export default function ChannelsPage() {
  const { analysis, members, hasData } = useHousehold();
  const head = members.find((m) => m.isHead) || members[0];
  const plan = analysis.plan.plans[1] || analysis.plan.plans[0];
  const msgs = hasData ? [
    ['in', 'Namaste! मेरा राशन कार्ड / pension check karna hai'],
    ['out', `Namaste${head?.name ? ' ' + head.name.split(' ')[0] : ''} 🙏 I am KaagazSaathi. I checked your household.`],
    ['out', `You may be missing ${inr(analysis.money.perYearLeft)} per year in benefits.`],
    plan ? ['out', `Fix ${plan.k} thing${plan.k > 1 ? 's' : ''} to unlock ${plan.count} schemes (${inr(plan.value)}):\n${plan.actions.map((a) => `• ${a.label} (${a.who})`).join('\n')}`] : ['out', 'Your papers look ready. You can apply today.'],
    ['in', 'Kahan jaana hai?'],
    ['out', `${plan?.actions[0] ? 'For the first fix: ' + (plan.actions[0].docType ? plan.actions[0].docType.replace(/_/g, ' ') : '') + '. ' : ''}Official fees are small. If anyone asks for much more, send us a photo of the receipt.`],
  ] : [['out', 'Set up a household first (or load the demo family) to see a live conversation here.']];
  return (
    <div className="container">
      <h1 className="page-title">WhatsApp and missed-call channel</h1>
      <div className="demo-banner">Mockup. The messages below are generated by the real engine from the current household. The WhatsApp / IVR connection is the roadmap item; it reuses the same profile and rules.</div>
      <div className="two-col">
        <section className="phone">
          <div className="phone-top">KaagazSaathi · WhatsApp</div>
          <div className="chat">{msgs.map(([d, t], i) => <div key={i} className={`bubble ${d}`}>{t}</div>)}</div>
        </section>
        <section className="card">
          <h2 className="card-title">Missed-call voice flow</h2>
          <ol className="reasons">
            <li>Citizen gives a missed call to the helpline number.</li>
            <li>System calls back and asks, in their language: "Press 1 for pension, 2 for scholarship, 3 for housing."</li>
            <li>It asks the same short questions as the voice onboarding and builds the same household profile.</li>
            <li>It reads out the top fix ("Get your bank passbook name corrected to match Aadhaar") and sends the dossier link by SMS.</li>
          </ol>
          <h3>Why this matters</h3>
          <p>The people who lose most to paperwork errors are often on feature phones with low literacy. Same rules engine, different front door.</p>
        </section>
      </div>
    </div>
  );
}
